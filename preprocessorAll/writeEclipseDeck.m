function info = writeEclipseDeck(deck, outFile, varargin)
%WRITEECLIPSEDECK Write a complete, runnable Eclipse .DATA deck from an MRST case.
%
% SYNOPSIS:
%   info = writeEclipseDeck(deck, 'CASE.DATA')
%
% The Eclipse sibling of writeCMGDeck. Where `modules/preprocessor`'s
% writeEclipse stops at the end of GRID and leaves PROPS, SOLUTION and
% SCHEDULE to the study, this writer emits all of them from the MRST case,
% so the deck runs as it stands in Eclipse, OPM Flow or any reader of the
% same format.
%
% PARAMETERS:
%   deck    - output of buildFullDeck.
%   outFile - path of the .DATA deck. The grid description is written beside
%             it as a .grdecl the deck INCLUDEs, exactly as in writeEclipse.
%
% OPTIONAL ('key', value):
%   'title'      - RUNSPEC title (default: base name, upper case).
%   'maxSteps'   - cap on the number of TSTEP entries written.
%   'wellRadius' - fallback wellbore radius [m].
%
% RETURNS:
%   info - struct with .deck, .grid, .manifest and record counts.
%
% SECTIONS
%   RUNSPEC  dimensions, phases, METRIC units, well and table limits
%   GRID     INCLUDE of the grid description (which opens its own EDIT
%            section for fracture pore volumes, depths and NNCs)
%   PROPS    PVT, relative permeability, capillary pressure, rock and
%            surface densities, all sampled from the MRST fluid
%   SOLUTION explicit PRESSURE / SWAT / SGAS arrays taken from state0
%   SUMMARY  field and well rates for comparison against the MRST run
%   SCHEDULE WELSPECS, COMPDAT with explicit connection factors, controls
%            and TSTEP
%
% UNITS: METRIC throughout - bar, m3/day, cP, kg/m3, mD, m, 1/bar.
%
% SEE ALSO: buildFullDeck, writeCMGDeck, writeEclipseModel.

    opt = struct('title', '', 'maxSteps', inf, 'wellRadius', 0.1);
    opt = merge_options(opt, varargin{:});

    [outDir, baseName, ext] = fileparts(outFile);
    if isempty(outDir), outDir = pwd; end
    if isempty(ext), ext = '.DATA'; outFile = fullfile(outDir, [baseName ext]); end
    if ~isfolder(outDir), mkdir(outDir); end

    title = opt.title;
    if isempty(title), title = upper(baseName); end

    gridFile = fullfile(outDir, [baseName '.grdecl']);
    gridInfo = writeEclipseModel(deck.res, gridFile);

    fid = fopen(outFile, 'w');
    assert(fid > 0, 'writeEclipseDeck:open', 'Could not open %s.', outFile);
    cleaner = onCleanup(@() fclose(fid));
    w = @(varargin) fprintf(fid, varargin{:});

    meta = deck.meta;
    res  = deck.res;
    ph   = meta.phases;
    dims = res.grid.dims;

    % ================================================================ HEAD
    w('-- =====================================================================\n');
    w('-- Complete Eclipse deck generated by writeEclipseDeck (MRST preprocessorAll)\n');
    w('--\n');
    w('-- Every section was derived from the MRST case - grid, rock, fractures,\n');
    w('-- PVT, rock-fluid, initialization, wells and schedule. Nothing is a\n');
    w('-- placeholder.\n');
    w('--\n');
    w('-- MRST model     : %s\n', meta.modelClass);
    w('-- Phases         : %s\n', localPhaseLabel(ph));
    w('-- Grid family    : %s   (%d x %d x %d)\n', meta.gridFamily, dims);
    w('-- Fracture model : %s\n', meta.fractureModel);
    w('-- Report steps   : %d\n', meta.nSteps);
    w('-- Generated      : %s\n', meta.created);
    if ~isempty(deck.warnings)
        w('--\n-- FIDELITY WARNINGS - the exported fluid differs from the MRST one:\n');
        for q = 1:numel(deck.warnings)
            w('--   - %s\n', regexprep(deck.warnings{q}, '\s+', ' '));
        end
    end
    w('-- =====================================================================\n\n');

    % ============================================================= RUNSPEC
    w('RUNSPEC\n\n');
    w('TITLE\n  %s /\n\n', title);
    w('DIMENS\n  %d %d %d /\n\n', dims);

    if ph.water, w('WATER\n'); end
    if ph.oil,   w('OIL\n');   end
    if ph.gas,   w('GAS\n');   end
    if deck.tab.singlePhaseFiller
        w('OIL\n');
        w('-- Single-phase water in MRST. Eclipse has no single-phase option, so\n');
        w('-- oil is declared with So = 0 everywhere and the water''s own\n');
        w('-- properties: with no oil in place and none injected, the oil\n');
        w('-- equations cannot affect the result.\n');
    end
    if ph.disgas, w('DISGAS\n'); end
    w('\nMETRIC\n\n');

    nW = localMaxWells(deck);
    nPerf = localMaxPerf(deck);
    w('WELLDIMS\n  %d %d %d %d /\n\n', max(nW,1), max(nPerf,1), max(nW,1), max(nW,1));
    w('TABDIMS\n  1 1 %d %d 1 %d /\n\n', ...
        max(numel(localFieldOr(deck.tab,'sw',0)), 20), ...
        max(numel(deck.tab.p), 20), max(numel(deck.tab.p), 20));

    sd = meta.startDate;
    w('START\n  %d ''%s'' %d /\n\n', sd(3), localMonth(sd(2)), sd(1));
    w('UNIFOUT\n\n');

    % ================================================================ GRID
    w('GRID\n\n');
    [~, gName, gExt] = fileparts(gridFile);
    w('INCLUDE\n  ''%s%s'' /\n\n', gName, gExt);
    % The include opens its own EDIT section when the model has fractures;
    % PROPS therefore follows it directly.

    % =============================================================== PROPS
    localWriteProps(w, deck);

    % ============================================================ SOLUTION
    localWriteSolution(w, deck);

    % ============================================================= SUMMARY
    localWriteSummary(w, deck);

    % ============================================================ SCHEDULE
    nWells = localWriteSchedule(w, deck, opt);

    info = gridInfo;
    info.deck = outFile;
    info.grid = gridFile;
    info.title = title;
    info.nWells = nWells;
    info.nSteps = numel(deck.steps.dtDays);
    info.warnings = deck.warnings;
    info.manifest = localWriteManifest(outDir, baseName, deck, info);
end


% ========================================================================
%                                PROPS
% ========================================================================

function localWriteProps(w, deck)
    tab = deck.tab;
    ph  = deck.meta.phases;
    pB  = localPa2bar(tab.p);

    w('PROPS\n\n');
    w('-- PVT and rock-fluid sampled from the MRST fluid''s own functions over\n');
    w('-- %.4g .. %.4g bar.\n\n', pB(1), pB(end));

    % ---- water ----------------------------------------------------------
    if ph.water
        f = tab.fit.water;
        w('PVTW\n');
        w('-- Pref[bar]      Bw          Cw[1/bar]     muW[cP]     Cvw[1/bar]\n');
        w('   %-12.5f %-11.7f %-13.6e %-11.7f %-13.6e /\n\n', ...
            localPa2bar(tab.water.pRef), tab.water.Bref, f.c*1e5, ...
            localPas2cp(tab.water.muRef), f.cmu*1e5);
    end

    % ---- oil ------------------------------------------------------------
    if ph.oil || tab.singlePhaseFiller
        if ph.disgas
            localWritePVTO(w, tab, pB);
        else
            w('PVDO\n');
            w('--  P[bar]        Bo         muO[cP]\n');
            for k = 1:numel(pB)
                w('   %-13.5f %-11.7f %-11.7f\n', pB(k), tab.oil.B(k), ...
                    localPas2cp(tab.oil.mu(k)));
            end
            w('/\n\n');
        end
    end

    % ---- gas ------------------------------------------------------------
    if ph.gas
        w('PVDG\n');
        w('--  P[bar]        Bg         muG[cP]\n');
        for k = 1:numel(pB)
            w('   %-13.5f %-13.9f %-11.7f\n', pB(k), tab.gas.B(k), ...
                localPas2cp(tab.gas.mu(k)));
        end
        w('/\n\n');
    end

    % ---- surface densities (Eclipse order: OIL WATER GAS) ---------------
    rho = tab.rhoS;
    if isnan(rho(2)), rho(2) = rho(1); end     % filler oil takes water's
    if isnan(rho(1)), rho(1) = 1000; end
    if isnan(rho(3)), rho(3) = 1; end
    w('DENSITY\n');
    w('-- oil        water      gas   [kg/m3]\n');
    w('   %-10.5f %-10.5f %-10.5f /\n\n', rho(2), rho(1), rho(3));

    % ---- rock -----------------------------------------------------------
    w('ROCK\n');
    w('-- Pref[bar]     Cr[1/bar]\n');
    w('   %-13.5f %-13.6e /\n\n', localPa2bar(tab.rock.pRef), tab.rock.cr*1e5);

    % ---- relative permeability ------------------------------------------
    if isfield(tab, 'sw') && isfield(tab, 'krow')
        w('SWOF\n');
        w('--  Sw          Krw         Krow        Pcow[bar]\n');
        for k = 1:numel(tab.sw)
            w('   %-11.7f %-11.7f %-11.7f %-11.7f\n', tab.sw(k), tab.krw(k), ...
                tab.krow(k), localPa2bar(tab.pcow(k)));
        end
        w('/\n\n');
    end

    if ph.gas && ph.oil
        w('SGOF\n');
        w('--  Sg          Krg         Krog        Pcog[bar]\n');
        for k = 1:numel(tab.sg)
            w('   %-11.7f %-11.7f %-11.7f %-11.7f\n', tab.sg(k), tab.krg(k), ...
                tab.krog(k), localPa2bar(tab.pcog(k)));
        end
        w('/\n\n');
    end
end


function localWritePVTO(w, tab, pB)
% Live oil. One saturated record per Rs, each closed by a '/', the whole
% table closed by a final '/'. Undersaturated branches are not sampled, so
% each record carries only its saturated point.
    w('PVTO\n');
    w('-- Rs[m3/m3]   P[bar]        Bo          muO[cP]\n');
    for k = 1:numel(pB)
        w('   %-12.6f %-13.5f %-11.7f %-11.7f /\n', tab.oil.rs(k), pB(k), ...
            tab.oil.B(k), localPas2cp(tab.oil.mu(k)));
    end
    w('/\n\n');
end


% ========================================================================
%                               SOLUTION
% ========================================================================

function localWriteSolution(w, deck)
    init = deck.init;
    ph   = deck.meta.phases;

    w('SOLUTION\n\n');
    if strcmp(init.mode, 'none')
        w('-- No state0 was supplied; equilibrate about the grid datum.\n');
        w('EQUIL\n  %.5f %.5f %.5f 0 %.5f 0 1 1 0 /\n\n', ...
            deck.res.grid.ztop, localPa2bar(deck.tab.pRef), ...
            deck.res.grid.zbot + 1000, deck.res.grid.ztop);
        return
    end

    w('-- Initialization taken cell by cell from the MRST state0 rather than\n');
    w('-- re-derived from contacts: state0 is what the MRST run started from,\n');
    w('-- so equilibrating here would introduce a difference never asked for.\n\n');

    % deckBlockArray places fracture cells at the padded addresses
    % buildCMGModel actually used; appending them to the end of the matrix
    % array would put them on the wrong blocks.
    res = deck.res;
    w('PRESSURE\n');
    localWriteArray(w, localPa2bar(deckBlockArray(res, init.pressure, init.pDatum)));
    w('/\n\n');

    [sw, sg] = localSaturations(init, ph, deck.tab);
    if ~isempty(sw)
        w('SWAT\n');
        localWriteArray(w, deckBlockArray(res, sw, 1.0));
        w('/\n\n');
    end
    if ph.gas && ~isempty(sg)
        w('SGAS\n');
        localWriteArray(w, deckBlockArray(res, sg, 0.0));
        w('/\n\n');
    end
    if ph.disgas && isfield(init, 'rs')
        w('RS\n');
        localWriteArray(w, deckBlockArray(res, init.rs, 0.0));
        w('/\n\n');
    end

    w('RPTRST\n  ''BASIC=2'' /\n\n');
end


function [sw, sg] = localSaturations(init, ph, tab)
    sw = []; sg = [];
    if isempty(init.s), return; end
    col = 0;
    if ph.water, col = col + 1; sw = init.s(:, col); end
    if ph.oil,   col = col + 1; end
    if ph.gas,   col = col + 1; sg = init.s(:, min(col, size(init.s, 2))); end
    if tab.singlePhaseFiller && isempty(sw)
        sw = ones(size(init.pressure));
    end
end


% ========================================================================
%                                SUMMARY
% ========================================================================

function localWriteSummary(w, deck)
    ph = deck.meta.phases;
    w('SUMMARY\n\n');
    w('-- Field totals, for comparison against the MRST run.\n');
    w('FPR\n');
    if ph.water, w('FWPR\nFWIR\nFWPT\nFWIT\n'); end
    if ph.oil,   w('FOPR\nFOPT\n'); end
    if ph.gas,   w('FGPR\nFGPT\n'); end
    w('\nWBHP\n  ''*'' /\n\n');
    if ph.water, w('WWPR\n  ''*'' /\n\n'); end
    if ph.oil,   w('WOPR\n  ''*'' /\n\n'); end
    w('EXCEL\n\n');
end


% ========================================================================
%                                SCHEDULE
% ========================================================================

function nWells = localWriteSchedule(w, deck, opt)
    steps = deck.steps;
    wells = deck.wells;
    nWells = 0;

    w('SCHEDULE\n\n');
    if isempty(wells)
        w('-- No wells were present in the MRST schedule.\n\n');
        if ~isempty(steps.dtDays)
            w('TSTEP\n');
            localWriteArray(w, steps.dtDays);
            w('/\n\n');
        end
        w('END\n');
        return
    end

    nWells = numel(wells(1).W);
    nStep = min(numel(steps.dtDays), opt.maxSteps);

    % WELSPECS and COMPDAT come from the first control period; both are
    % static in an MRST schedule, where only the controls change.
    localWriteWelspecs(w, wells(1).W);
    localWriteCompdat(w, wells(1).W, opt);

    lastCtrl = 0;
    pending = [];
    for s = 1:nStep
        c = steps.control(s);
        if c ~= lastCtrl
            if ~isempty(pending)
                w('TSTEP\n');
                localWriteArray(w, pending);
                w('/\n\n');
                pending = [];
            end
            localWriteControls(w, wells(c).W, c);
            lastCtrl = c;
        end
        pending(end+1) = steps.dtDays(s); %#ok<AGROW>
    end
    if ~isempty(pending)
        w('TSTEP\n');
        localWriteArray(w, pending);
        w('/\n\n');
    end

    w('END\n');
end


function localWriteWelspecs(w, W)
    w('WELSPECS\n');
    w('-- name   group   i   j   refDepth[m]   phase\n');
    for k = 1:numel(W)
        wl = W(k);
        i = wl.uba(1,1); j = wl.uba(1,2);
        rd = wl.refDepth;
        if ~isfinite(rd) || rd == 0, rdStr = '1*'; else, rdStr = sprintf('%.4f', rd); end
        w('   ''%s'' ''G1'' %d %d %s ''%s'' /\n', wl.name, i, j, rdStr, ...
            localWelspecsPhase(wl));
    end
    w('/\n\n');
end


function localWriteCompdat(w, W, opt)
% Connection factors are MRST's well indices, written explicitly in item 8.
% Eclipse's radial model is deliberately not used: on a padded fracture or
% connection-list grid the block geometry is a placeholder, so a computed
% well index would be meaningless.
    ecl = centi*poise*meter^3/(day*barsa);
    w('COMPDAT\n');
    w('-- name   i  j  k1 k2  state  satTab  CF[cP.m3/day/bar]  diam  Kh  skin\n');
    for k = 1:numel(W)
        wl = W(k);
        r = wl.radius; if ~(r > 0), r = opt.wellRadius; end
        for q = 1:size(wl.uba, 1)
            w('   ''%s'' %d %d %d %d ''OPEN'' 1* %.8e %.5f 1* 0 /\n', ...
                wl.name, wl.uba(q,1), wl.uba(q,2), wl.uba(q,3), wl.uba(q,3), ...
                wl.wi(q)/ecl, 2*r);
        end
    end
    w('/\n\n');
end


function localWriteControls(w, W, ctrl)
    w('-- ---- control period %d ------------------------------------------\n', ctrl);
    inj = W([W.isInjector]);
    prd = W(~[W.isInjector]);

    if ~isempty(inj)
        w('WCONINJE\n');
        w('-- name   phase   state   mode    rate[m3/day]   1*   bhp[bar]\n');
        for k = 1:numel(inj)
            wl = inj(k);
            st = localState(wl);
            if strcmpi(wl.type, 'bhp')
                w('   ''%s'' ''%s'' ''%s'' ''BHP'' 1* 1* %.5f /\n', ...
                    wl.name, upper(wl.phase), st, localPa2bar(wl.val));
            else
                w('   ''%s'' ''%s'' ''%s'' ''RATE'' %.6f 1* 1* /\n', ...
                    wl.name, upper(wl.phase), st, ...
                    convertTo(abs(wl.val), meter^3/day));
            end
        end
        w('/\n\n');
    end

    if ~isempty(prd)
        w('WCONPROD\n');
        w('-- name   state   mode    orat  wrat  grat  lrat  resv  bhp[bar]\n');
        for k = 1:numel(prd)
            wl = prd(k);
            st = localState(wl);
            if strcmpi(wl.type, 'bhp')
                w('   ''%s'' ''%s'' ''BHP'' 5* %.5f /\n', wl.name, st, ...
                    localPa2bar(wl.val));
            else
                w('   ''%s'' ''%s'' ''LRAT'' 3* %.6f 1* 1* /\n', wl.name, st, ...
                    convertTo(abs(wl.val), meter^3/day));
            end
        end
        w('/\n\n');
    end
end


function s = localState(wl)
    if wl.status, s = 'OPEN'; else, s = 'SHUT'; end
end


function ph = localWelspecsPhase(wl)
    if wl.isInjector
        ph = upper(wl.phase);
    else
        ph = 'OIL';
    end
end


% ========================================================================
%                               UTILITIES
% ========================================================================

function localWriteArray(w, v)
    n = numel(v);
    for k = 1:8:n
        j = min(k+7, n);
        w('  %s\n', strjoin(compose('%.7g', v(k:j)), ' '));
    end
end


function b = localPa2bar(pa),  b  = pa / barsa;            end
function c = localPas2cp(pas), c  = pas / (centi*poise);   end


function n = localMaxWells(deck)
    n = 0;
    for c = 1:numel(deck.wells)
        n = max(n, numel(deck.wells(c).W));
    end
end


function n = localMaxPerf(deck)
    n = 0;
    for c = 1:numel(deck.wells)
        for k = 1:numel(deck.wells(c).W)
            n = max(n, size(deck.wells(c).W(k).uba, 1));
        end
    end
end


function m = localMonth(k)
    names = {'JAN','FEB','MAR','APR','MAY','JUN','JLY','AUG','SEP','OCT','NOV','DEC'};
    m = names{min(max(round(k),1),12)};
end


function s = localPhaseLabel(ph)
    parts = {};
    if ph.water, parts{end+1} = 'water'; end
    if ph.oil,   parts{end+1} = 'oil';   end
    if ph.gas,   parts{end+1} = 'gas';   end
    s = strjoin(parts, '-');
    if isfield(ph, 'disgas') && ph.disgas, s = [s ' (live oil)']; end
end


function v = localFieldOr(s, name, dflt)
    if isfield(s, name), v = s.(name); else, v = dflt; end
end


function manifestFile = localWriteManifest(outDir, baseName, deck, info)
    manifestFile = fullfile(outDir, [baseName '_fulldeck_manifest.json']);
    m = struct( ...
        'schema', 'MRST-full-deck-eclipse-v1', ...
        'meta', deck.meta, ...
        'deck', info.deck, ...
        'grid', info.grid, ...
        'nWells', info.nWells, ...
        'nSteps', info.nSteps, ...
        'warnings', {deck.warnings});
    fid = fopen(manifestFile, 'w');
    assert(fid > 0, 'writeEclipseDeck:manifest', 'Could not open %s.', manifestFile);
    c = onCleanup(@() fclose(fid));
    fprintf(fid, '%s\n', jsonencode(m, 'PrettyPrint', true));
end
