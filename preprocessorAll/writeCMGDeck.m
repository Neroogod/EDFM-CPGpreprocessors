function info = writeCMGDeck(deck, outFile, varargin)
%WRITECMGDECK Write a complete, runnable CMG dataset from an MRST case.
%
% SYNOPSIS:
%   info = writeCMGDeck(deck, 'case.dat')
%
% Where `modules/preprocessor`'s writeCMG exports the reservoir description
% and leaves the fluid model, initialization and schedule to be supplied in
% Builder, this writer emits all of them, taken from the MRST case, so the
% dataset runs in IMEX as it stands.
%
% PARAMETERS:
%   deck    - output of buildFullDeck.
%   outFile - path of the dataset to write. The reservoir description goes
%             beside it as a .inc that the dataset *INCLUDEs, exactly as in
%             writeCMG.
%
% OPTIONAL ('key', value):
%   'title'    - TITLE1 text (default: the file's base name, upper case).
%   'maxSteps' - cap on the number of TIME cards written (default all).
%   'wellRadius' - fallback wellbore radius [m] when the MRST well has none.
%
% RETURNS:
%   info - struct with .dataset, .include, .manifest and record counts.
%
% SECTION LAYOUT
%   The keyword order follows a working IMEX 2024.30 black-oil dataset:
%   I/O control, reservoir description (grid via *INCLUDE), component/PVT
%   model, rock-fluid, initialization, numerical, then the recurrent RUN
%   section with wells and TIME cards.
%
%   *GRID is written in the dataset rather than the include, for the reason
%   documented in writeCMG: Builder rejects the fundamental grid definition
%   when it arrives through an *INCLUDE.
%
% UNITS
%   The dataset is written *INUNIT *SI, so pressures are kPa, rates m3/day,
%   permeability md, lengths m and viscosity cp - CMG's SI set, not strict
%   SI. Every conversion happens here, at the point of writing.
%
% SEE ALSO: buildFullDeck, writeEclipseDeck, writeCMGModel.

    opt = struct('title', '', 'maxSteps', inf, 'wellRadius', 0.1);
    opt = merge_options(opt, varargin{:});

    [outDir, baseName, ext] = fileparts(outFile);
    if isempty(outDir), outDir = pwd; end
    if isempty(ext), ext = '.dat'; outFile = fullfile(outDir, [baseName ext]); end
    if ~isfolder(outDir), mkdir(outDir); end

    title = opt.title;
    if isempty(title), title = upper(baseName); end

    % Reservoir description: identical to writeCMG's include.
    incFile = fullfile(outDir, [baseName '.inc']);
    incInfo = writeCMGModel(deck.res, incFile);

    fid = fopen(outFile, 'w');
    assert(fid > 0, 'writeCMGDeck:open', 'Could not open %s.', outFile);
    cleaner = onCleanup(@() fclose(fid));
    w = @(varargin) fprintf(fid, varargin{:});

    meta = deck.meta;
    res  = deck.res;
    tab  = deck.tab;
    ph   = meta.phases;

    % ================================================================ HEAD
    w('** =====================================================================\n');
    w('** Complete %s dataset generated by writeCMGDeck (MRST preprocessorAll)\n', meta.simulator);
    w('**\n');
    w('** Every section below was derived from the MRST case - grid, rock,\n');
    w('** fractures, PVT, rock-fluid, initialization, wells and schedule.\n');
    w('** Nothing is a placeholder.\n');
    w('**\n');
    w('** MRST model    : %s\n', meta.modelClass);
    w('** Phases        : %s\n', localPhaseLabel(ph));
    w('** Grid family   : %s   (%d x %d x %d)\n', meta.gridFamily, res.grid.dims);
    w('** Fracture model: %s\n', meta.fractureModel);
    w('** Report steps  : %d\n', meta.nSteps);
    w('** Generated     : %s\n', meta.created);
    if ~isempty(deck.warnings)
        w('**\n** FIDELITY WARNINGS - the exported fluid differs from the MRST one:\n');
        for q = 1:numel(deck.warnings)
            w('**   - %s\n', localWrap(deck.warnings{q}));
        end
    end
    w('** =====================================================================\n');
    w('RESULTS SIMULATOR IMEX %s\n\n', localVersion(meta));

    w('TITLE1 ''%s''\n', title);
    w('INUNIT SI\n');
    w('WPRN GRID TIME\n');
    w('OUTPRN GRID NONE\n');
    w('OUTPRN RES NONE\n');
    w('WSRF GRID TIME\n');
    w('WSRF WELL 1\n');
    w('OUTSRF GRID PRES SW SO SG\n');
    w('OUTSRF WELL LAYER NONE\n\n');

    % ================================================== RESERVOIR / GRID
    hdr = cmgGridHeader(res);
    for q = 1:numel(hdr)
        w('%s\n', hdr{q});
    end
    [~, incName, incExt] = fileparts(incFile);
    w('INCLUDE ''%s%s''\n\n', incName, incExt);

    % Rock compressibility, referenced to the initialization pressure so the
    % pore volume IMEX reports is the pore volume that was exported.
    pRefkPa = localPa2kPa(tab.rock.pRef);
    w('CPOR %.6g\n', tab.rock.cr * 1e3);       % 1/kPa
    w('PRPOR %.6g\n\n', pRefkPa);

    % ============================================================ FLUID
    localWritePVT(w, deck);

    % ======================================================== ROCKFLUID
    localWriteRockFluid(w, deck);

    % ========================================================== INITIAL
    localWriteInitial(w, deck);

    % ======================================================== NUMERICAL
    w('*NUMERICAL\n');
    w('*DTMAX 30\n');
    w('*DTMIN 1e-6\n');
    w('*NORM *PRESS 100\n\n');

    % ======================================================== RECURRENT
    w('*RUN\n');
    sd = meta.startDate;
    w('*DATE %d %d %d\n', sd(1), sd(2), sd(3));
    w('*DTWELL 1\n\n');

    nWells = localWriteRecurrent(w, deck, opt);

    w('*STOP\n');

    % ============================================================ RETURN
    info = incInfo;
    info.dataset = outFile;
    info.include = incFile;
    info.title = title;
    info.nWells = nWells;
    info.nSteps = numel(deck.steps.dtDays);
    info.warnings = deck.warnings;
    info.manifest = localWriteManifest(outDir, baseName, deck, info);
end


% ========================================================================
%                              PVT SECTION
% ========================================================================

function localWritePVT(w, deck)
% IMEX's fluid model has two shapes, and which one is legal depends on
% whether the oil carries dissolved gas:
%
%   live oil  - a multi-row saturated *PVT table (p, Rs, Bo, Eg, viso, visg)
%               in which Rs and Bo must both INCREASE with pressure, because
%               the oil swells as more gas dissolves;
%   dead oil  - a SINGLE row at a reference pressure, with the pressure
%               dependence supplied by *CO / *CVO instead. A dead oil's Bo
%               decreases with pressure, which the saturated table forbids,
%               so a multi-row table is rejected outright ("entry 2 for Rs
%               is constant or decreasing", IMEX subroutine SETTBP).
%
% Both forms are taken from the IMEX 2024.30 templates: TPL/cmb/mxcmb001.dat
% for the live-oil table and TPL/frr/mxfrr003.dat for the dead-oil form.
    tab = deck.tab;
    ph  = deck.meta.phases;

    w('** ---------------------------------------------------------------------\n');
    w('** Fluid model, derived from the MRST fluid''s own functions sampled\n');
    w('** over %.4g .. %.4g kPa.\n', localPa2kPa(tab.p(1)), localPa2kPa(tab.p(end)));
    w('** ---------------------------------------------------------------------\n');

    if ph.oil && ph.gas
        assert(ph.disgas, 'writeCMGDeck:deadOil3P', ...
            ['A three-phase model without dissolved gas (disgas = false) has ', ...
             'no single-table IMEX form: the saturated *PVT table requires an ', ...
             'increasing Rs, and the dead-oil single-row form carries no gas ', ...
             'pressure dependence. Enable disgas, or drop the gas phase.']);
        w('*MODEL *BLACKOIL\n\n');
        localWriteLiveOilPVT(w, tab);
    elseif ph.oil && ph.water
        w('*MODEL *OILWATER\n\n');
        localWriteDeadOilPVT(w, tab);
    elseif ph.water && ~ph.oil && ~ph.gas
        % Single-phase water. Exported as OILWATER with the oil given the
        % water's own properties and So = 0 everywhere: with no oil in place
        % and none injected, the oil equations never influence the answer, so
        % this is a faithful mapping rather than an invented second phase.
        w('** Single-phase water model. IMEX has no single-phase option, so this\n');
        w('** is written as *OILWATER with So = 0 everywhere and the oil given\n');
        w('** the water''s own properties. With no oil in place and none\n');
        w('** injected, the oil equations cannot affect the result.\n');
        w('*MODEL *OILWATER\n\n');
        localWriteDeadOilPVT(w, tab);
    elseif ph.gas && ph.water
        w('*MODEL *GASWATER\n\n');
        localWriteGasWaterPVT(w, tab);
    else
        error('writeCMGDeck:phases', ...
            'No IMEX fluid model is written for the phase combination "%s".', ...
            localPhaseLabel(ph));
    end

    if ph.water
        localWriteWaterProps(w, tab);
    end
    w('\n');
end


function localWriteLiveOilPVT(w, tab)
% Multi-row saturated table. Rs and Bo are checked here rather than left to
% IMEX so a non-monotone MRST fluid is reported in MATLAB, where it can be
% acted on, instead of as a SETTBP error after the fact.
    p   = localPa2kPa(tab.p);
    rs  = tab.oil.rs;
    Bo  = tab.oil.B;
    Eg  = 1 ./ tab.gas.B;
    muo = localPas2cp(tab.oil.mu);
    mug = localPas2cp(tab.gas.mu);

    localAssertIncreasing(rs, 'Rs');
    localAssertIncreasing(Bo, 'Bo');

    w('*PVT\n');
    w('**      p(kPa)          rs         bo          eg        viso       visg\n');
    for k = 1:numel(p)
        w('  %12.5f %11.5f %10.6f %11.5f %10.6f %10.7f\n', ...
            p(k), rs(k), Bo(k), Eg(k), muo(k), mug(k));
    end
    w('\n');
    localWriteDensities(w, tab, true);
    localWriteOilComp(w, tab);
end


function localWriteDeadOilPVT(w, tab)
% Single row at the reference pressure; *CO and *CVO carry the pressure
% dependence. This is the form IMEX's own oil-water templates use.
    fito = tab.fit.oil;
    w('*PVT\n');
    w('** Dead oil: one row at the reference pressure, with the pressure\n');
    w('** dependence carried by *CO and *CVO below. A multi-row saturated\n');
    w('** table is not legal here - it requires Rs and Bo to increase with\n');
    w('** pressure, and a dead oil''s Bo decreases.\n');
    w('**      p(kPa)          rs         bo          eg        viso       visg\n');
    w('  %12.5f %11.5f %10.6f %11.5f %10.6f %10.7f\n', ...
        localPa2kPa(tab.oil.pRef), 0.0, tab.oil.Bref, 1.0, ...
        localPas2cp(tab.oil.muRef), 0.01);
    w('\n');
    localWriteDensities(w, tab, false);
    localWriteOilComp(w, tab);
    if ~isfinite(fito.maxRelErr) || fito.maxRelErr > 1e-3
        w('** NOTE: the oil''s pressure dependence is not exactly exponential;\n');
        w('** *CO reproduces the MRST function to %.2e over the sampled range.\n', ...
            fito.maxRelErr);
    end
end


function localWriteGasWaterPVT(w, tab)
    p   = localPa2kPa(tab.p);
    Eg  = 1 ./ tab.gas.B;
    mug = localPas2cp(tab.gas.mu);
    w('*PVT\n');
    w('**      p(kPa)          rs         bo          eg        viso       visg\n');
    for k = 1:numel(p)
        w('  %12.5f %11.5f %10.6f %11.5f %10.6f %10.7f\n', ...
            p(k), 0.0, 1.0, Eg(k), 1.0, mug(k));
    end
    w('\n');
    localWriteDensities(w, tab, true);
end


function localWriteDensities(w, tab, haveGas)
% IMEX warns and assumes 1 kg/m3 if *DENSITY *GAS is absent, even in models
% with no gas phase, so all three are always written.
    rho = tab.rhoS;
    if isnan(rho(2)), rho(2) = 800; end
    if isnan(rho(1)), rho(1) = 1000; end
    w('*DENSITY *OIL   %.6f\n', rho(2));
    if haveGas && ~isnan(rho(3))
        w('*DENSITY *GAS   %.6f\n', rho(3));
    else
        w('*DENSITY *GAS   1.0\n');
        w('** No gas phase in the MRST model; this density is never used, but\n');
        w('** IMEX warns and assumes a value when the keyword is absent.\n');
    end
    w('*DENSITY *WATER %.6f\n', rho(1));
end


function localWriteOilComp(w, tab)
% Oil compressibility and viscosity pressure coefficient. IMEX requires one
% of *CO, *COT/*BOT or the PVT table to define co.
    fito = tab.fit.oil;
    w('*CO    %.6e\n', fito.c   * 1e-3);      % 1/Pa -> 1/kPa
    w('*CVO   %.6e\n', fito.cmu * 1e-3);
end


function localWriteWaterProps(w, tab)
% Water as reference volume factor plus compressibilities. The fit residual
% was measured in sampleFluidTables and reported in deck.warnings.
    fitw = tab.fit.water;
    w('*BWI   %.8f\n', tab.water.Bref);
    w('*CW    %.6e\n', fitw.c   * 1e-3);      % 1/Pa -> 1/kPa
    w('*REFPW %.6f\n', localPa2kPa(tab.water.pRef));
    w('*VWI   %.8f\n', localPas2cp(tab.water.muRef));
    w('*CVW   %.6e\n', fitw.cmu * 1e-3);
end


function localAssertIncreasing(v, name)
    d = diff(v(:));
    assert(all(d > 0), 'writeCMGDeck:nonMonotone', ...
        ['%s is not strictly increasing over the sampled pressure range, so ', ...
         'the saturated *PVT table IMEX requires cannot be written. Narrow ', ...
         '''pRange'', reduce ''nP'', or check the MRST fluid.'], name);
end


% ========================================================================
%                            ROCKFLUID SECTION
% ========================================================================

function localWriteRockFluid(w, deck)
    tab = deck.tab;
    ph  = deck.meta.phases;

    w('** ---------------------------------------------------------------------\n');
    w('** Rock-fluid tables sampled from the MRST fluid''s relperm functions.\n');
    w('** ---------------------------------------------------------------------\n');
    w('*ROCKFLUID\n');
    w('*RPT 1\n\n');

    % *SWT is written whenever the deck has a water-oil system, including the
    % single-phase-water case where the oil is a documented filler.
    if isfield(tab, 'sw') && isfield(tab, 'krow')
        % *SWT: sw, krw, krow[, pcow]. krow is the oil relperm in the
        % water-oil system, tabulated against water saturation.
        hasPc = any(abs(tab.pcow) > 0);
        w('*SWT\n');
        if hasPc
            w('**      sw         krw        krow      pcow(kPa)\n');
        else
            w('**      sw         krw        krow\n');
        end
        for k = 1:numel(tab.sw)
            if hasPc
                w('  %10.6f %11.7f %11.7f %12.5f\n', tab.sw(k), ...
                    tab.krw(k), tab.krow(k), localPa2kPa(tab.pcow(k)));
            else
                w('  %10.6f %11.7f %11.7f\n', tab.sw(k), tab.krw(k), tab.krow(k));
            end
        end
        w('\n');
    end

    if ph.gas && ph.oil
        % *SLT is tabulated against liquid saturation sl = 1 - sg, so the
        % gas table is written in reverse order of sg.
        hasPc = any(abs(tab.pcog) > 0);
        w('*SLT\n');
        if hasPc
            w('**      sl         krg        krog      pcog(kPa)\n');
        else
            w('**      sl         krg        krog\n');
        end
        idx = numel(tab.sg):-1:1;
        for q = idx
            sl = 1 - tab.sg(q);
            if hasPc
                w('  %10.6f %11.7f %11.7f %12.5f\n', sl, tab.krg(q), ...
                    tab.krog(q), localPa2kPa(tab.pcog(q)));
            else
                w('  %10.6f %11.7f %11.7f\n', sl, tab.krg(q), tab.krog(q));
            end
        end
        w('\n');
    end

    if ph.water && ph.gas && ~ph.oil
        w('*SWT\n');
        w('**      sw         krw        krg\n');
        for k = 1:numel(tab.sw)
            w('  %10.6f %11.7f %11.7f\n', tab.sw(k), tab.krw(k), tab.krg(k));
        end
        w('\n');
    end
end


% ========================================================================
%                            INITIAL SECTION
% ========================================================================

function localWriteInitial(w, deck)
    init = deck.init;
    ph   = deck.meta.phases;
    res  = deck.res;

    w('** ---------------------------------------------------------------------\n');
    w('** Initialization taken cell by cell from the MRST state0, rather than\n');
    w('** re-derived from contacts: state0 is what the MRST run actually\n');
    w('** started from, so equilibrating here would introduce a difference\n');
    w('** that was never asked for.\n');
    w('** ---------------------------------------------------------------------\n');
    w('*INITIAL\n');

    if strcmp(init.mode, 'none')
        w('** No state0 was supplied; a uniform datum initialization is written.\n');
        w('*VERTICAL *DEPTH_AVE\n');
        w('*REFDEPTH %.5f\n', res.grid.ztop);
        w('*REFPRES  %.5f\n\n', localPa2kPa(deck.tab.pRef));
        return
    end

    w('*USER_INPUT\n\n');

    % Pressure, one value per block. deckBlockArray places fracture cells at
    % the padded addresses buildCMGModel actually used; appending them to the
    % end of the matrix array would put them on the wrong blocks.
    w('*PRES *ALL\n');
    localWriteArray(w, localPa2kPa(deckBlockArray(res, init.pressure, init.pDatum)));
    w('\n');

    % Saturations. IMEX takes SW always, and SG additionally in a
    % three-phase model; oil saturation is the remainder.
    [sw, sg] = localSaturations(init, ph);
    if ph.water
        w('*SW *ALL\n');
        localWriteArray(w, deckBlockArray(res, sw, 1.0));
        w('\n');
    end
    if ph.gas && ph.oil
        w('*SG *ALL\n');
        localWriteArray(w, deckBlockArray(res, sg, 0.0));
        w('\n');
    end
end


function [sw, sg] = localSaturations(init, ph)
    sw = []; sg = [];
    if isempty(init.s), return; end
    col = 0;
    if ph.water, col = col + 1; sw = init.s(:, col); end
    if ph.oil,   col = col + 1; end
    if ph.gas,   col = col + 1; sg = init.s(:, min(col, size(init.s,2))); end
end


% ========================================================================
%                           RECURRENT SECTION
% ========================================================================

function nWells = localWriteRecurrent(w, deck, opt)
% Wells and TIME cards. A control period's wells are re-declared whenever
% the control index changes, which is how IMEX expresses MRST's piecewise
% constant schedule.
    steps = deck.steps;
    wells = deck.wells;
    nWells = 0;

    if isempty(wells)
        w('** No wells were present in the MRST schedule.\n');
        if ~isempty(steps.tEndDays)
            w('*TIME %.6f\n', steps.tEndDays(end));
        else
            w('*TIME 1\n');
        end
        return
    end

    nWells = numel(wells(1).W);
    nStep = min(numel(steps.dtDays), opt.maxSteps);
    lastCtrl = 0;

    for s = 1:nStep
        c = steps.control(s);
        if c ~= lastCtrl
            localWriteWellSet(w, wells(c).W, c, opt);
            lastCtrl = c;
        end
        w('*TIME %.6f\n', steps.tEndDays(s));
    end
    w('\n');
end


function localWriteWellSet(w, W, ctrl, opt)
    if isempty(W), return; end
    w('\n** ---- control period %d ------------------------------------------\n', ctrl);
    w('** Well indices are MRST''s own (*PERF *WI, md.m). CMG''s radial model\n');
    w('** is deliberately not used: it would be applied to the exported block\n');
    w('** geometry rather than the geometry MRST computed the WI from.\n\n');

    for k = 1:numel(W)
        wl = W(k);
        w('*WELL ''%s''\n', wl.name);
        if wl.isInjector
            w('*INJECTOR *MOBWEIGHT ''%s''\n', wl.name);
            w('*INCOMP *%s\n', upper(wl.phase));
            switch lower(wl.type)
                case 'bhp'
                    w('*OPERATE *MAX *BHP %.6f\n', localPa2kPa(wl.val));
                otherwise
                    w('*OPERATE *MAX *ST%s %.6f\n', localPhaseTag(wl.phase), ...
                        convertTo(abs(wl.val), meter^3/day));
            end
        else
            w('*PRODUCER ''%s''\n', wl.name);
            switch lower(wl.type)
                case 'bhp'
                    w('*OPERATE *MIN *BHP %.6f\n', localPa2kPa(wl.val));
                otherwise
                    w('*OPERATE *MAX *STL %.6f\n', ...
                        convertTo(abs(wl.val), meter^3/day));
            end
        end

        r = wl.radius; if ~(r > 0), r = opt.wellRadius; end
        w('*GEOMETRY *K %.5f 0.37 1.0 0.0\n', r);
        w('*PERF *WI ''%s''\n', wl.name);
        w('**  i  j  k        wi(md.m)\n');
        for q = 1:size(wl.uba, 1)
            w('   %d %d %d   %.8e\n', wl.uba(q,1), wl.uba(q,2), wl.uba(q,3), ...
                localWI2mdm(wl.wi(q)));
        end
        w('\n');
    end
end


% ========================================================================
%                              UTILITIES
% ========================================================================

function localWriteArray(w, v)
% Numeric array, six values per line.
    n = numel(v);
    for k = 1:6:n
        j = min(k+5, n);
        w('  %s\n', strjoin(compose('%.7g', v(k:j)), ' '));
    end
end


function kPa = localPa2kPa(pa)
    kPa = pa / 1000;
end


function cp = localPas2cp(pas)
    cp = pas / (centi*poise);
end


function v = localWI2mdm(wi)
% MRST's well index is a transmissibility (m3 in SI); CMG's *PERF *WI is in
% md.m. Same conversion the existing preprocessor applies to connection
% transmissibilities, written with the full unit product so the intent is
% explicit even though `meter` is 1 in MRST's SI system.
    v = wi / (milli*darcy*meter);
end


function tag = localPhaseTag(phase)
    switch upper(char(string(phase)))
        case 'WATER', tag = 'W';
        case 'GAS',   tag = 'G';
        otherwise,    tag = 'O';
    end
end


function s = localPhaseLabel(ph)
    parts = {};
    if ph.water, parts{end+1} = 'water'; end
    if ph.oil,   parts{end+1} = 'oil';   end
    if ph.gas,   parts{end+1} = 'gas';   end
    s = strjoin(parts, '-');
    if isfield(ph, 'disgas') && ph.disgas
        s = [s ' (live oil)'];
    end
end


function v = localVersion(meta)
    v = char(string(meta.cmgVersion));
    if isempty(v) || strcmpi(v, 'unspecified'), v = '2024.30'; end
end


function s = localWrap(s)
    s = regexprep(char(s), '\s+', ' ');
end


function manifestFile = localWriteManifest(outDir, baseName, deck, info)
    manifestFile = fullfile(outDir, [baseName '_fulldeck_manifest.json']);
    m = struct( ...
        'schema', 'MRST-full-deck-CMG-v1', ...
        'meta', deck.meta, ...
        'dataset', info.dataset, ...
        'include', info.include, ...
        'nWells', info.nWells, ...
        'nSteps', info.nSteps, ...
        'pvtSamples', numel(deck.tab.p), ...
        'satSamples', numel(localFieldOr(deck.tab, 'sw', [])), ...
        'warnings', {deck.warnings});
    fid = fopen(manifestFile, 'w');
    assert(fid > 0, 'writeCMGDeck:manifest', 'Could not open %s.', manifestFile);
    c = onCleanup(@() fclose(fid));
    fprintf(fid, '%s\n', jsonencode(m, 'PrettyPrint', true));
end


function v = localFieldOr(s, name, dflt)
    if isfield(s, name), v = s.(name); else, v = dflt; end
end
