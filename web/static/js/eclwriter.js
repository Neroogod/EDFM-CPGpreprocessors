// Browser port of writeEclipseModel.m and writeEclipse.m's stub deck.
//
// Same contract as the CMG writer: output must be byte-identical to the
// MATLAB version for the same model, verified in selftest.html.
//
// Eclipse arrays terminate with `/` and comments start with `--`; otherwise
// the wrapping and number formats are the same as the CMG path, which is why
// fmt.js is shared rather than duplicated.

import { wrapValues } from "./fmt.js";

/** writeEclipseModel.m — the grid description (.grdecl). */
export function writeEclipseInclude(model) {
  if (model.meta.fractureModel !== "matrix") {
    throw new Error(
      `Eclipse export covers matrix grids only; this model is ` +
      `"${model.meta.fractureModel}".`);
  }

  const L = [];
  const meta = model.meta;
  const g = model.grid;
  const d = g.dims;
  const nTot = d[0] * d[1] * d[2];
  const props = model.props;

  L.push("-- =====================================================================");
  L.push("-- MRST -> Eclipse grid description (generated by writeEclipseModel)");
  L.push(`-- GRID_FAMILY      : ${meta.gridFamily}   (MRST type: ${meta.gridType})`);
  L.push(`-- FRACTURE_MODEL   : ${meta.fractureModel}`);
  L.push("-- UNITS            : METRIC, permeability mD, lengths m");
  L.push(`-- BLOCKS           : ${d[0]} x ${d[1]} x ${d[2]} = ${nTot} (${meta.counts.inactive} inactive)`);
  L.push("-- =====================================================================");
  L.push("");

  switch (g.kind) {
    case "corner":
      L.push("SPECGRID");
      L.push(` ${d[0]} ${d[1]} ${d[2]} 1 F /`);
      L.push("");
      array(L, "COORD", g.coord, "%.6f");
      array(L, "ZCORN", g.zcorn, "%.6f");
      break;

    case "cart":
    case "vari":
      array(L, "DXV", g.di, "%.6f");
      array(L, "DYV", g.dj, "%.6f");
      array(L, "DZV", g.dk, "%.6f");
      array(L, "TOPS", blockTops(d, g.dk, g.ztop), "%.6f");
      break;

    default:
      throw new Error(`grid kind ${g.kind} has no Eclipse representation here`);
  }

  if (meta.counts.inactive > 0) array(L, "ACTNUM", props.active, "%d");
  array(L, "PERMX", props.permi, "%.6e");
  array(L, "PERMY", props.permj, "%.6e");
  array(L, "PERMZ", props.permk, "%.6e");
  array(L, "PORO",  props.poro,  "%.6f");

  return L.join("\n") + "\n";
}

/** writeEclipse.m's localWriteStub — RUNSPEC/GRID skeleton, nothing invented. */
export function writeEclipseStub(model, includeName, title) {
  const L = [];
  const meta = model.meta;
  const d = model.grid.dims;
  const nTot = d[0] * d[1] * d[2];

  L.push("-- =====================================================================");
  L.push("-- Eclipse deck generated by writeEclipse (MRST preprocessor)");
  L.push("--");
  L.push("-- Contains the GRID ONLY. Every number in the grid description came");
  L.push("-- from the MRST model; nothing has been invented.");
  L.push("--");
  L.push(`-- Grid family    : ${meta.gridFamily}   (MRST type: ${meta.gridType})`);
  L.push(`-- Fracture model : ${meta.fractureModel}`);
  L.push(`-- Blocks         : ${d[0]} x ${d[1]} x ${d[2]} = ${nTot} (${meta.counts.inactive} inactive)`);
  L.push(`-- Depth range    : ${model.grid.ztop.toFixed(3)} .. ${model.grid.zbot.toFixed(3)} m`);
  L.push("--");
  L.push("-- Still to be supplied:");
  L.push("--   PROPS     PVT and relative permeability");
  L.push("--   REGIONS   if the model needs them");
  L.push("--   SOLUTION  equilibration or explicit initial state");
  L.push("--   SUMMARY   requested vectors");
  L.push("--   SCHEDULE  wells and time stepping");
  L.push("-- =====================================================================");
  L.push("RUNSPEC");
  L.push("");
  L.push("TITLE");
  L.push(` ${title} /`);
  L.push("");
  L.push("DIMENS");
  L.push(` ${d[0]} ${d[1]} ${d[2]} /`);
  L.push("");
  L.push("METRIC");
  L.push("");
  L.push("GRID");
  L.push("");
  L.push("INCLUDE");
  L.push(` '${includeName}' /`);
  L.push("");
  L.push("-- End of preprocessor output. Add PROPS onwards below.");

  return L.join("\n") + "\n";
}

//---------------------------------------------------------------- helpers

/** TOPS carries the true top depth of every block, not just layer 1. */
function blockTops(dims, dk, ztop) {
  const [nx, ny, nz] = dims;
  const layerTop = new Float64Array(nz);
  let z = ztop;
  for (let k = 0; k < nz; k++) { layerTop[k] = z; z += dk[k]; }

  const out = new Float64Array(nx * ny * nz);
  let p = 0;
  for (let k = 0; k < nz; k++) {
    const v = layerTop[k];
    for (let c = 0; c < nx * ny; c++) out[p++] = v;
  }
  return out;
}

function array(L, keyword, values, spec) {
  L.push(keyword);
  wrapValues(L, values, spec, 6);   // pushes a trailing blank line
  // Eclipse terminates a data block with a slash. wrapValues left a blank at
  // the end, so replace it rather than appending after it.
  L[L.length - 1] = "/";
  L.push("");
}
