// Browser port of writeCMGModel.m and writeCMG.m's stub deck.
//
// Output must be byte-identical to the MATLAB writers for the same model —
// that equality is the regression test that keeps the two implementations
// from drifting. Every banner line, blank line and space is deliberate.

import { wrapValues, isConstant, formatter } from "./fmt.js";
import { gridHeader } from "./cmgmodel.js";

/** writeCMGModel.m — the reservoir description (.inc). */
export function writeInclude(model) {
  const L = [];
  const meta = model.meta;
  const dims = model.grid.dims;
  const props = model.props;
  const nTot = dims[0] * dims[1] * dims[2];

  L.push("** =====================================================================");
  L.push("** MRST -> CMG reservoir description (generated by writeCMGModel)");
  L.push(`** TARGET_SIMULATOR : ${meta.simulator}`);
  L.push(`** TARGET_VERSION   : ${meta.cmgVersion}`);
  L.push(`** GRID_FAMILY      : ${meta.gridFamily}   (MRST type: ${meta.gridType})`);
  L.push(`** FRACTURE_MODEL   : ${meta.fractureModel}`);
  L.push(`** DETECTED_BY      : ${meta.detection}`);
  L.push(`** UNITS            : SI, permeability mD, transmissibility ${meta.transUnit}`);
  L.push(`** BLOCKS           : ${dims[0]} x ${dims[1]} x ${dims[2]} = ${nTot} (${meta.counts.inactive} inactive)`);
  L.push(`** CONNECTIONS      : ${meta.counts.connections} explicit, ${meta.counts.multipliers} multipliers`);
  L.push("**");
  L.push("** This file holds ARRAYS ONLY. The dataset that includes it must declare");
  L.push("** the fundamental grid first - Builder rejects *GRID from inside an");
  L.push("** *INCLUDE and renders an empty grid. Put these two cards ahead of the");
  L.push("** *INCLUDE line:");
  for (const h of gridHeader(model)) L.push(`**   ${h}`);
  L.push("** =====================================================================");
  L.push("");

  // ---- grid geometry ----
  const g = model.grid;
  switch (g.kind) {
    case "corner":
      array(L, "*COORD", g.coord, "%.6f");
      array(L, "*ZCORN", g.zcorn, "%.6f");
      break;

    case "cart":
      // Uniform: one value per direction.
      L.push(`*DI *CON ${formatter("%.8g")(g.di[0])}`);
      L.push(`*DJ *CON ${formatter("%.8g")(g.dj[0])}`);
      L.push(`*DK *CON ${formatter("%.8g")(g.dk[0])}`);
      dtop(L, g.dims, g.ztop);
      break;

    case "vari":
      // localVarVector wraps at 8 per line, not 6.
      varVector(L, "*DI *IVAR", g.di);
      varVector(L, "*DJ *JVAR", g.dj);
      varVector(L, "*DK *KVAR", g.dk);
      dtop(L, g.dims, g.ztop);
      break;

    default:
      throw new Error(`grid kind ${g.kind} not supported in the browser`);
  }
  L.push("");

  // ---- properties ----
  arrayOrConst(L, "*PERMI", props.permi, "%.6e");
  arrayOrConst(L, "*PERMJ", props.permj, "%.6e");
  arrayOrConst(L, "*PERMK", props.permk, "%.6e");
  arrayOrConst(L, "*POR",   props.poro,  "%.6f");

  // ---- null blocks ----
  if (meta.counts.inactive > 0) {
    L.push(`** ${meta.counts.inactive} inactive blocks`);
    array(L, "*NULL *ALL", props.active, "%d");
  }

  return L.join("\n") + "\n";
}

/** writeCMG.m's localWriteStubDeck — grid only, no invented properties. */
export function writeStubDeck(model, includeName, title) {
  const L = [];
  const meta = model.meta;
  const d = model.grid.dims;
  const nTot = d[0] * d[1] * d[2];
  const version = (!meta.cmgVersion || meta.cmgVersion === "unspecified")
    ? "2024.30" : meta.cmgVersion;

  L.push("** =====================================================================");
  L.push(`** ${meta.simulator} dataset generated by writeCMG (MRST preprocessor)`);
  L.push("**");
  L.push("** Contains the GRID ONLY. Every number in the reservoir description");
  L.push("** came from the MRST model; nothing has been invented.");
  L.push("**");
  L.push(`** Grid family    : ${meta.gridFamily}   (MRST type: ${meta.gridType})`);
  L.push(`** Fracture model : ${meta.fractureModel}`);
  L.push(`** Blocks         : ${d[0]} x ${d[1]} x ${d[2]} = ${nTot} (${meta.counts.inactive} inactive)`);
  L.push(`** Depth range    : ${model.grid.ztop.toFixed(3)} .. ${model.grid.zbot.toFixed(3)} m`);
  L.push("**");
  L.push("** Still to be supplied, in Builder or by hand:");
  L.push("**   *MODEL / component and PVT data");
  L.push("**   *ROCKFLUID  relative permeability and capillary pressure");
  L.push("**   *INITIAL    initialization, reference depth and pressure, contacts");
  L.push("**   *NUMERICAL  solver controls");
  L.push("**   RUN section: wells, constraints and time steps");
  L.push("**   *CPOR / *PRPOR rock compressibility");
  L.push("** =====================================================================");
  L.push(`RESULTS SIMULATOR ${meta.simulator} ${version}`);
  L.push("");
  L.push(`TITLE1 '${title}'`);
  L.push("INUNIT SI");
  L.push("");
  for (const h of gridHeader(model)) L.push(h);
  L.push(`*INCLUDE '${includeName}'`);
  L.push("");
  // writeCMG.m emits a wells block only when wells exist; the stub deck says
  // nothing about them otherwise. (The "No wells were supplied" line belongs
  // to the runnable deck, not this one.)
  if (model.wells && model.wells.length) {
    L.push("** Wells exported from MRST, with explicit well indices. Uncomment");
    L.push("** and move below RUN once the fluid model is in place.");
    L.push("**");
  }
  L.push("** ---------------------------------------------------------------------");
  L.push("** Section markers only - no data. Populate above RUN (fluid model,");
  L.push("** rock-fluid, initialization) and below it (wells, constraints, dates).");
  L.push("** As written this deck is incomplete: open it in Builder, not IMEX.");
  L.push("RUN");
  L.push("STOP");

  return L.join("\n") + "\n";
}

export function writeManifest(model, includeName, datName) {
  return JSON.stringify({
    schema: "MRST-CMG-preprocessor-v1",
    simulator: model.meta.simulator,
    cmgVersion: model.meta.cmgVersion,
    gridFamily: model.meta.gridFamily,
    mrstGridType: model.meta.gridType,
    fractureModel: model.meta.fractureModel,
    detection: model.meta.detection,
    unitSystem: model.meta.unitSystem,
    transmissibilityUnit: model.meta.transUnit,
    dims: model.grid.dims,
    counts: model.meta.counts,
    include: includeName,
    dataset: datName,
    producedBy: "EDFM Grid Builder (browser)",
  }, null, 2) + "\n";
}

//---------------------------------------------------------------- helpers

function array(L, keyword, values, spec) {
  L.push(keyword);
  wrapValues(L, values, spec, 6);
}

/** writeCMGModel.m's localVarVector: 8 values per line, %.8g. */
function varVector(L, keyword, values) {
  L.push(keyword);
  wrapValues(L, values, "%.8g", 8);
}

/** localDtop: ni*nj copies of the top depth, %.6f, 6 per line. */
function dtop(L, dims, ztop) {
  const n = dims[0] * dims[1];
  const v = new Float64Array(n).fill(ztop);
  L.push("** depth to the top of layer 1");
  array(L, "*DTOP", v, "%.6f");
}

function arrayOrConst(L, keyword, values, spec) {
  if (values.length === 0) return;
  if (isConstant(values)) {
    const f = formatter(spec);
    L.push(`${keyword} *CON ${f(values[0])}`);
    L.push("");
  } else {
    array(L, `${keyword} *ALL`, values, spec);
  }
}
