function info = writeCMGModel(model, incFile)
% Write a CMG reservoir-description include file from a built CMG model.
%
% SYNOPSIS:
%   info = writeCMGModel(model, 'case.inc')
%
% PARAMETERS:
%   model   - struct from buildCMGModel.
%   incFile - path of the include file to write.
%
% RETURNS:
%   info - struct with the written path and the record counts.
%
% CARD USAGE (verified against the CMG 2024.30 keyword manual installed on
% this machine; see preprocessor_implementation.md section 2.1):
%   *GRID *CART|*VARI|*CORNER   fundamental grid
%   *DI/*DJ/*DK *CON|*IVAR|...  block sizes
%   *DTOP                       ni*nj depths to the top layer
%   *PERMI/J/K, *POR            properties, *CON when constant
%   *NULL *ALL                  inactive blocks
%   *VOLMOD *ALL                bulk-volume multipliers (placeholder grids)
%   *SCONNECT                   explicit connections, transmissibility md.m
%
% SEE ALSO:
%   buildCMGModel, writeCMG

fid = fopen(incFile, 'w');
assert(fid > 0, 'writeCMGModel:open', 'Could not open %s for writing.', incFile);
cleaner = onCleanup(@() fclose(fid)); %#ok<NASGU>
w = @(varargin) fprintf(fid, varargin{:});

meta = model.meta;
dims = model.grid.dims;
props = model.props;

% ---------------------------------------------------------------- banner
w('** =====================================================================\n');
w('** MRST -> CMG reservoir description (generated by writeCMGModel)\n');
w('** TARGET_SIMULATOR : %s\n', meta.simulator);
w('** TARGET_VERSION   : %s\n', meta.cmgVersion);
w('** GRID_FAMILY      : %s   (MRST type: %s)\n', meta.gridFamily, meta.gridType);
w('** FRACTURE_MODEL   : %s\n', meta.fractureModel);
w('** DETECTED_BY      : %s\n', meta.detection);
w('** UNITS            : SI, permeability mD, transmissibility %s\n', meta.transUnit);
w('** BLOCKS           : %d x %d x %d = %d (%d inactive)\n', dims, ...
    prod(dims), meta.counts.inactive);
w('** CONNECTIONS      : %d explicit, %d multipliers\n', ...
    meta.counts.connections, meta.counts.multipliers);
w('**\n');
w('** This file holds ARRAYS ONLY. The dataset that includes it must declare\n');
w('** the fundamental grid first - Builder rejects *GRID from inside an\n');
w('** *INCLUDE and renders an empty grid. Put these two cards ahead of the\n');
w('** *INCLUDE line:\n');
hdr = cmgGridHeader(model);
for q = 1:numel(hdr)
    w('**   %s\n', hdr{q});
end
w('** =====================================================================\n\n');

% ------------------------------------------------------------ grid block
switch model.grid.kind
    case 'cart'
        w('*DI *CON %.8g\n', model.grid.di(1));
        w('*DJ *CON %.8g\n', model.grid.dj(1));
        w('*DK *CON %.8g\n', model.grid.dk(1));
        localDtop(w, fid, dims, model.grid.ztop);

    case 'vari'
        localVarVector(fid, '*DI *IVAR', model.grid.di);
        localVarVector(fid, '*DJ *JVAR', model.grid.dj);
        localVarVector(fid, '*DK *KVAR', model.grid.dk);
        if isempty(props.depth)
            % Per-block depths are written as *DEPTH-TOP further down when
            % they exist; *DTOP would then be a conflicting specification.
            localDtop(w, fid, dims, model.grid.ztop);
        end

    case 'corner'
        localArray(fid, '*COORD', model.grid.coord, '%.6f');
        localArray(fid, '*ZCORN', model.grid.zcorn, '%.6f');

    case 'connlist'
        w('** Connection-list pseudo-grid: CMG has no unstructured grid type.\n');
        w('** Placeholder geometry only - true pore volume enters through\n');
        w('** *VOLMOD, true depth through *DEPTH-TOP, and the entire\n');
        w('** connectivity through the *SCONNECT list below.\n');
        w('**\n');
        w('** *VARI rather than *CART: every block sits in the single layer\n');
        w('** K=1, and only *VARI permits blocks of one layer to lie at\n');
        w('** different depths (*CART requires a layer to share one depth).\n');
        w('*DI *CON 1.0\n*DJ *CON 1.0\n*DK *CON 1.0\n');
        % Depth comes from *DEPTH-TOP below; *DTOP would conflict with it.

    otherwise
        error('writeCMGModel:kind', 'Unhandled grid kind %s', model.grid.kind);
end
w('\n');

% ------------------------------------------------------------ properties
localArrayOrConst(fid, '*PERMI', props.permi, '%.6e');
localArrayOrConst(fid, '*PERMJ', props.permj, '%.6e');
localArrayOrConst(fid, '*PERMK', props.permk, '%.6e');
localArrayOrConst(fid, '*POR',   props.poro,  '%.6f');

% ------------------------------------------------------------ null blocks
nInactive = nnz(~props.active);
if nInactive > 0
    w('** %d inactive blocks\n', nInactive);
    localArray(fid, '*NULL *ALL', double(props.active), '%d');
end

% ------------------------------------------------- volume / depth overrides
if ~isempty(props.volmod)
    w('** True pore volume via bulk-volume multipliers. Each block appears\n');
    w('** exactly once: *VOLMOD accumulates when a block is repeated.\n');
    localArray(fid, '*VOLMOD *ALL', props.volmod, '%.8e');
end
if isfield(props, 'porvol') && ~isempty(props.porvol)
    w('** Pore volume [m3] taken straight from the MRST model. *PORVOL\n');
    w('** overrides the porosity-times-bulk-volume calculation, so this is\n');
    w('** exact regardless of how CMG evaluates placeholder block geometry.\n');
    localArray(fid, '*PORVOL *ALL', props.porvol, '%.8e');
end
if ~isempty(props.depth)
    % *DEPTH-TOP is the array form; *DEPTH addresses a single block only.
    localArray(fid, '*DEPTH-TOP *ALL', props.depth, '%.6f');
end

% ------------------------------------------- transmissibility base + mods
% IMEX rejects "*TRANSI with direct MOD" unless the fundamental grid already
% carries a transmissibility assignment, so establish the unit base first.
isolate = [];
if isfield(model, 'isolate'), isolate = model.isolate; end
needsTransMod = ~isempty(model.mult) || ~isempty(isolate) || ...
    (strcmp(model.grid.kind, 'connlist') && ~isempty(model.conn));
if needsTransMod
    w('** Fundamental transmissibility assignment; *MOD below requires it.\n');
    w('*TRANSI *CON 1.0\n*TRANSJ *CON 1.0\n*TRANSK *CON 1.0\n\n');
end

% ---------------------------------------------- padding-region isolation
if ~isempty(isolate)
    w('** Isolate the fracture padding region: its geometry is a placeholder,\n');
    w('** so every automatic connection there - and across the interface to\n');
    w('** the last matrix layer - is removed. Fracture cells then communicate\n');
    w('** only through the explicit *SCONNECT list below.\n');
    for q = 1:numel(isolate)
        r = isolate(q).range;
        w('%s *MOD %d:%d %d:%d %d:%d = %g\n', isolate(q).keyword, ...
            r(1), r(2), r(3), r(4), r(5), r(6), isolate(q).value);
    end
    w('\n');
end

% ----------------------------------------------------------- connections
if ~isempty(model.conn)
    if strcmp(model.grid.kind, 'connlist')
        w('** The placeholder grid''s own I-direction connections carry no\n');
        w('** meaning and are removed before the real connectivity is added.\n');
        w('*TRANSI *MOD 1:%d 1 1 = 0\n\n', dims(1));
    end
    w('** Explicit connections, transmissibility in %s\n', meta.transUnit);
    w('*SCONNECT\n');
    fprintf(fid, '  %d %d %d  %d %d %d  %.8e\n', model.conn');
    w('\n');
end

% ----------------------------------------------------------- multipliers
if ~isempty(model.mult)
    dirKw = {'*TRANSI', '*TRANSJ', '*TRANSK'};
    for d = 1:3
        rows = model.mult(model.mult(:,1) == d, :);
        if isempty(rows), continue; end
        w('%s *MOD\n', dirKw{d});
        fprintf(fid, '  %d %d %d = %.8e\n', rows(:, 2:5)');
        w('\n');
    end
end

info = struct('include', incFile, ...
    'dims', dims, ...
    'simulator', meta.simulator, ...
    'gridFamily', meta.gridFamily, ...
    'fractureModel', meta.fractureModel, ...
    'counts', meta.counts);
end

%--------------------------------------------------------------------------
function localDtop(w, fid, dims, ztop)
% *DTOP takes ni*nj values. *CART additionally requires them all equal.
n = dims(1)*dims(2);
w('** depth to the top of layer 1\n');
localArray(fid, '*DTOP', repmat(ztop, n, 1), '%.6f');
end

%--------------------------------------------------------------------------
function localVarVector(fid, keyword, values)
fprintf(fid, '%s\n', keyword);
localWrap(fid, values(:), '%.8g', 8);
end

%--------------------------------------------------------------------------
function localArrayOrConst(fid, keyword, values, fmt)
% Constant arrays are far smaller (and faster to parse) as *CON.
v = values(:);
if isempty(v), return; end
if (max(v) - min(v)) <= 1e-12*max(1, abs(max(v)))
    fprintf(fid, ['%s *CON ' fmt '\n\n'], keyword, v(1));
else
    localArray(fid, [keyword ' *ALL'], v, fmt);
end
end

%--------------------------------------------------------------------------
function localArray(fid, keyword, values, fmt)
fprintf(fid, '%s\n', keyword);
localWrap(fid, values(:), fmt, 6);
end

%--------------------------------------------------------------------------
function localWrap(fid, v, fmt, perLine)
n = numel(v);
full = perLine*floor(n/perLine);
if full > 0
    rowFmt = [repmat([' ' fmt], 1, perLine) '\n'];
    fprintf(fid, rowFmt, reshape(v(1:full), perLine, []));
end
if full < n
    fprintf(fid, [' ' fmt], v(full+1:end));
    fprintf(fid, '\n');
end
fprintf(fid, '\n');
end
