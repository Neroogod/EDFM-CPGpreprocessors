function info = writeEclipse(G, outFile, varargin)
% Export an MRST grid to an Eclipse-format deck. Sibling of writeCMG.
%
% SYNOPSIS:
%   info = writeEclipse(G, 'case.DATA')
%   info = writeEclipse(G, 'case.DATA', 'grdecl', grdecl)   % corner-point
%
% PARAMETERS:
%   G       - any MRST grid: cartGrid, tensorGrid or processGRDECL. The grid
%             family is detected from G, as in writeCMG.
%   outFile - path of the .DATA file. The grid description is written
%             alongside it as a .grdecl that the deck INCLUDEs.
%
% OPTIONAL ('key', value):
%   'rock'      - rock structure (default G.rock)
%   'grdecl'    - corner-point description; required for processGRDECL grids
%   'datum'     - depth [m] to the top of the grid
%   'hostDeck'  - 'stub' (default) writes a RUNSPEC/GRID skeleton carrying
%                 the grid and nothing else; 'none' writes only the include
%   'title'     - TITLE string
%
% NO PROPERTY IS INVENTED. The deck carries geometry, permeability, porosity
% and the active-block flags. PROPS, SOLUTION and SCHEDULE are left to the
% study, exactly as writeCMG leaves the CMG fluid model alone.
%
% SEE ALSO:
%   writeCMG, writeEclipseModel, buildCMGModel

opt = struct('rock', [], 'grdecl', [], 'datum', [], 'model', 'auto', ...
             'hostDeck', 'stub', 'title', '', 'tol', 1e-5, 'wells', []);
opt = merge_options(opt, varargin{:});
hostDeck = validatestring(opt.hostDeck, {'stub', 'none'});

model = buildCMGModel(G, opt.rock, ...
    'model', opt.model, 'grdecl', opt.grdecl, 'datum', opt.datum, ...
    'tol', opt.tol, 'wells', opt.wells);

[outDir, baseName, ext] = fileparts(outFile);
if isempty(outDir), outDir = pwd; end
if isempty(ext), ext = '.DATA'; outFile = fullfile(outDir, [baseName ext]); end
if ~isfolder(outDir), mkdir(outDir); end

incFile = fullfile(outDir, [baseName '.grdecl']);
info = writeEclipseModel(model, incFile);

info.dataset = '';
info.title = opt.title;
if isempty(info.title), info.title = upper(baseName); end
info.hostDeck = hostDeck;

if strcmp(hostDeck, 'stub')
    info.dataset = localWriteStub(outFile, incFile, model, info.title);
end
info.nWells = numel(model.wells);
end

%--------------------------------------------------------------------------
function datFile = localWriteStub(outFile, incFile, model, title)
% A RUNSPEC/GRID skeleton around the grid description. Deliberately stops at
% the end of GRID: PROPS, SOLUTION and SCHEDULE are the study's to write, and
% inventing a fluid model would put numbers in front of the user that came
% from nowhere.
datFile = outFile;
fid = fopen(datFile, 'w');
assert(fid > 0, 'writeEclipse:openDeck', 'Could not open %s.', datFile);
cleaner = onCleanup(@() fclose(fid)); %#ok<NASGU>
w = @(varargin) fprintf(fid, varargin{:});

[~, incName, incExt] = fileparts(incFile);
meta = model.meta;
d = model.grid.dims;

w('-- =====================================================================\n');
w('-- Eclipse deck generated by writeEclipse (MRST preprocessor)\n');
w('--\n');
w('-- Contains the GRID ONLY. Every number in the grid description came\n');
w('-- from the MRST model; nothing has been invented.\n');
w('--\n');
w('-- Grid family    : %s   (MRST type: %s)\n', meta.gridFamily, meta.gridType);
w('-- Fracture model : %s\n', meta.fractureModel);
w('-- Blocks         : %d x %d x %d = %d (%d inactive)\n', d, prod(d), ...
    meta.counts.inactive);
w('-- Depth range    : %.3f .. %.3f m\n', model.grid.ztop, model.grid.zbot);
w('--\n');
w('-- Still to be supplied:\n');
w('--   PROPS     PVT and relative permeability\n');
w('--   REGIONS   if the model needs them\n');
w('--   SOLUTION  equilibration or explicit initial state\n');
w('--   SUMMARY   requested vectors\n');
w('--   SCHEDULE  wells and time stepping\n');
w('-- =====================================================================\n');

w('RUNSPEC\n\n');
w('TITLE\n %s /\n\n', title);
w('DIMENS\n %d %d %d /\n\n', d);
w('METRIC\n\n');
w('GRID\n\n');
w('INCLUDE\n ''%s%s'' /\n\n', incName, incExt);

localWriteWells(fid, model);

w('-- End of preprocessor output. Add PROPS onwards below.\n');
end

%--------------------------------------------------------------------------
function localWriteWells(fid, model)
% Wells are written commented out, because they belong in SCHEDULE and this
% deck stops at the end of GRID. Uncomment the block once PROPS, REGIONS and
% SOLUTION are in place.
%
% Connection factors are given explicitly in COMPDAT item 8 rather than left
% to Eclipse's radial model. On a padding-cell or connection-list grid the
% block geometry is a placeholder, so a computed well index would be
% meaningless; MRST already knows the right value.
wells = model.wells;
if isempty(wells), return; end

w = @(varargin) fprintf(fid, varargin{:});
mdm = milli*darcy*meter;
ecl = centi*poise*meter^3/(day*barsa);

w('-- ---------------------------------------------------------------------\n');
w('-- %d well(s) exported from MRST, with explicit connection factors.\n', numel(wells));
w('-- These belong in SCHEDULE; uncomment once the sections above it exist.\n');
w('--\n');
w('-- SCHEDULE\n');
w('--\n');
w('-- WELSPECS\n');
for k = 1:numel(wells)
    wl = wells(k);
    phase = 'OIL';
    if wl.isInjector, phase = upper(wl.comp); end
    w('--  ''%s'' ''G1'' %d %d 1* ''%s'' /\n', wl.name, wl.uba(1,1), wl.uba(1,2), phase);
end
w('-- /\n--\n');

w('-- COMPDAT\n');
w('--  well  I  J  K1 K2  status  satnum  connection factor [cP.m3/day/bar]\n');
for k = 1:numel(wells)
    wl = wells(k);
    for p = 1:size(wl.uba, 1)
        w('--  ''%s'' %d %d %d %d ''OPEN'' 1* %.8e /\n', wl.name, ...
            wl.uba(p,1), wl.uba(p,2), wl.uba(p,3), wl.uba(p,3), ...
            wl.wi(p)*(mdm/ecl));
    end
end
w('-- /\n--\n');

for k = 1:numel(wells)
    wl = wells(k);
    if wl.isInjector
        if strcmpi(wl.type, 'bhp')
            w('-- WCONINJE\n--  ''%s'' ''%s'' ''OPEN'' ''BHP'' 2* %.6f /\n-- /\n', ...
                wl.name, upper(wl.comp), convertTo(wl.val, barsa));
        else
            w('-- WCONINJE\n--  ''%s'' ''%s'' ''OPEN'' ''RATE'' %.6e /\n-- /\n', ...
                wl.name, upper(wl.comp), convertTo(abs(wl.val), meter^3/day));
        end
    else
        if strcmpi(wl.type, 'bhp')
            w('-- WCONPROD\n--  ''%s'' ''OPEN'' ''BHP'' 5* %.6f /\n-- /\n', ...
                wl.name, convertTo(wl.val, barsa));
        else
            w('-- WCONPROD\n--  ''%s'' ''OPEN'' ''LRAT'' 3* %.6e /\n-- /\n', ...
                wl.name, convertTo(abs(wl.val), meter^3/day));
        end
    end
end
w('-- ---------------------------------------------------------------------\n\n');
end
