function info = writeEclipseCoarseCPEDFM(coarse, W, outFile, varargin)
% Export a coarse CPEDFM model (from buildCoarseCPEDFM) as a
% connection-list Eclipse deck for screening studies.
%
% SYNOPSIS:
%   info = writeEclipseCoarseCPEDFM(coarse, W, 'COARSE.DATA')
%
% PARAMETERS:
%   coarse - struct from buildCoarseCPEDFM.
%   W      - MRST well structure on the FINE grid (from addWell); each
%            well is mapped to the coarse blocks its cells fall in, and
%            the fine well indices are summed per block and written as
%            explicit connection factors (COMPDAT item 8), so no
%            Peaceman calculation is attempted on the dummy geometry.
%   outFile- path of the .DATA file to write.
%
% OPTIONAL ('key', value):
%   'p0'    - initial pressure [Pa] (default 200 bar)
%   'dt'    - schedule steps [s] (default 10 x 30 days)
%   'title' - deck title
%
% REPRESENTATION: the coarse blocks become cells of a dummy Nc x 1 x 1
% grid whose geometry is irrelevant: pore volumes and depths enter
% through EDIT overrides, every geometric transmissibility is zeroed,
% and the entire connectivity is the aggregated NNC list. Because TPFA
% simulators consume only (cell pair, transmissibility), this
% reproduces the coarse model exactly in any NNC-capable simulator.

opt = struct('p0', 200*barsa, 'dt', repmat(30*day, 10, 1), ...
             'title', 'CPEDFM_COARSE_EXPORT');
opt = merge_options(opt, varargin{:});

nc = coarse.nBlocks;
transUnit = centi*poise*meter^3/(day*barsa);

% ---- map wells to coarse blocks with aggregated connection factors ----
wells = struct('name', {}, 'type', {}, 'val', {}, 'comp', {}, ...
    'blocks', {}, 'CF', {});
for w = 1:numel(W)
    blk = coarse.partition(W(w).cells);
    [ublk, ~, ic] = unique(blk);
    cf = accumarray(ic, W(w).WI);
    if strcmpi(W(w).type, 'rate'), ty = 'rate'; else, ty = 'bhp'; end
    if W(w).compi(1) > 0.5, comp = 'WATER'; else, comp = 'OIL'; end
    wells(end+1) = struct('name', W(w).name, 'type', ty, ...
        'val', W(w).val, 'comp', comp, 'blocks', ublk, 'CF', cf); %#ok<AGROW>
end

% ---- write ----------------------------------------------------------
fid = fopen(outFile, 'w');
assert(fid > 0, 'Could not open %s for writing.', outFile);
c = onCleanup(@() fclose(fid));
w = @(varargin) fprintf(fid, varargin{:});

w('-- Generated by writeEclipseCoarseCPEDFM (CPEDFM-export module)\n');
w('-- Coarse connection-list model: %d blocks, %d connections\n', ...
    nc, size(coarse.pairs, 1));
w('-- Geometry is placeholder; physics enters via PORV/DEPTH/NNC.\n\n');

w('RUNSPEC\n\nTITLE\n %s /\n\n', opt.title);
w('DIMENS\n %d 1 1 /\n\n', nc);
w('OIL\nWATER\n\nMETRIC\n\nTABDIMS\n 1 1 20 20 /\n\n');
w('WELLDIMS\n %d %d 2 %d /\n\n', numel(wells), ...
    max(arrayfun(@(x) numel(x.blocks), wells)), numel(wells));
w('START\n 1 JAN 2026 /\n\nUNIFOUT\n\n');

w('GRID\n\n');
w('DX\n %d*100.0 /\n\n', nc);
w('DY\n %d*100.0 /\n\n', nc);
w('DZ\n %d*10.0 /\n\n', nc);
w('TOPS\n %d*1000.0 /\n\n', nc);
w('PORO\n %d*0.2 /\n\n', nc);
w('PERMX\n %d*100.0 /\n\nPERMY\n %d*100.0 /\n\nPERMZ\n %d*100.0 /\n\n', nc, nc, nc);

w('-- coarse connectivity (trans in cP.m3/day/bar)\n');
w('NNC\n');
Tecl = convertTo(coarse.T, transUnit);
for q = 1:size(coarse.pairs, 1)
    w(' %d 1 1  %d 1 1  %.8e /\n', coarse.pairs(q,1), coarse.pairs(q,2), Tecl(q));
end
w('/\n\n');

w('EDIT\n\n');
w('-- kill the placeholder geometric connections\n');
w('TRANX\n %d*0.0 /\n\n', nc);
w('-- true block pore volumes [m3] and depths [m]\n');
writeVec(fid, 'PORV', coarse.pv, '%.8e');
writeVec(fid, 'DEPTH', coarse.depth, '%.6f');

w('PROPS\n\n');
w('SWOF\n');
sw = linspace(0, 1, 11)';
for q = 1:numel(sw)
    w(' %.4f %.6f %.6f 0.0\n', sw(q), sw(q)^2, (1-sw(q))^2);
end
w('/\n\n');
w('PVTW\n 200.0 1.0 4.0E-5 0.5 0.0 /\n\n');
w('PVCDO\n 200.0 1.0 1.0E-5 5.0 0.0 /\n\n');
w('ROCK\n 200.0 4.35E-5 /\n\n');
w('DENSITY\n 800.0 1000.0 1.2 /\n\n');

w('SOLUTION\n\n');
w('EQUIL\n %.4f %.4f %.4f 0.0 1* 0.0 1* 1* 0 /\n\n', ...
    mean(coarse.depth), convertTo(opt.p0, barsa), max(coarse.depth) + 1000);

w('SUMMARY\n\nFPR\nWBHP\n/\nWOPR\n/\nWWIR\n/\n\n');

w('SCHEDULE\n\n');
w('WELSPECS\n');
for q = 1:numel(wells)
    w(' ''%s'' ''G'' %d 1 1* ''%s'' /\n', wells(q).name, ...
        wells(q).blocks(1), upper(wells(q).comp));
end
w('/\n\n');
w('COMPDAT\n');
for q = 1:numel(wells)
    for b = 1:numel(wells(q).blocks)
        % explicit connection factor (item 8), METRIC cP.m3/day/bar
        w(' ''%s'' %d 1 1 1 ''OPEN'' 1* %.8e /\n', wells(q).name, ...
            wells(q).blocks(b), convertTo(wells(q).CF(b), transUnit));
    end
end
w('/\n\n');
for q = 1:numel(wells)
    if strcmpi(wells(q).type, 'rate') && strcmpi(wells(q).comp, 'WATER')
        w('WCONINJE\n ''%s'' ''WATER'' ''OPEN'' ''RATE'' %.6e 1* 1000.0 /\n/\n\n', ...
            wells(q).name, convertTo(wells(q).val, meter^3/day));
    elseif strcmpi(wells(q).type, 'bhp') && strcmpi(wells(q).comp, 'WATER')
        w('WCONINJE\n ''%s'' ''WATER'' ''OPEN'' ''BHP'' 1* 1* %.4f /\n/\n\n', ...
            wells(q).name, convertTo(wells(q).val, barsa));
    else
        w('WCONPROD\n ''%s'' ''OPEN'' ''BHP'' 5* %.4f /\n/\n\n', ...
            wells(q).name, convertTo(wells(q).val, barsa));
    end
end
w('TSTEP\n');
w(' %.4f', convertTo(opt.dt, day));
w(' /\n\nEND\n');

info = struct('nBlocks', nc, 'nConn', size(coarse.pairs,1), ...
    'Tecl', Tecl, 'wells', wells);
end

function writeVec(fid, kw, v, fmt)
fprintf(fid, '%s\n', kw);
fprintf(fid, [' ' fmt ' ' fmt ' ' fmt ' ' fmt ' ' fmt ' ' fmt '\n'], ...
    v(1:6*floor(numel(v)/6)));
rem = v(6*floor(numel(v)/6)+1:end);
if ~isempty(rem)
    fprintf(fid, [' ' fmt], rem);
    fprintf(fid, '\n');
end
fprintf(fid, '/\n\n');
end
