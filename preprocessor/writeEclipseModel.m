function info = writeEclipseModel(model, incFile)
% Write an Eclipse-format grid description from a built CMG model.
%
% SYNOPSIS:
%   info = writeEclipseModel(model, 'case.grdecl')
%
% PARAMETERS:
%   model   - struct from buildCMGModel. The struct is simulator-neutral
%             despite the name: it carries geometry, properties and
%             connections with no CMG-specific content, which is what lets
%             one builder feed both writers.
%   incFile - path of the include file to write.
%
% KEYWORDS EMITTED:
%   corner-point   SPECGRID, COORD, ZCORN
%   Cartesian      DXV, DYV, DZV, TOPS
%   both           ACTNUM (when any block is inactive), PERMX/Y/Z, PORO
%
% UNITS: METRIC throughout - permeability mD, lengths m, porosity fraction.
% These are the same units buildCMGModel already produced for CMG, so no
% conversion happens here.
%
% FRACTURES: the padding cells buildCMGModel created are written as ordinary
% blocks; their physics enters through an EDIT section that follows the grid
% keywords in the same file -
%
%   PORV     true fracture pore volume (Eclipse's direct pore-volume override)
%   DEPTH    true fracture-cell depth, so gravity is right
%   TRANX/Y/Z zeroed over the padding, isolating it geometrically
%   NNC      one record per connection, transmissibility in METRIC
%   MULTX/Y/Z pEDFM and CPEDFM seals on logical-neighbour faces
%
% This mirrors what the CMG writer does with *PORVOL, *DEPTH-TOP,
% *TRANS?*MOD and *SCONNECT, from the same model struct.
%
% SEE ALSO:
%   buildCMGModel, writeEclipse, writeCMGModel

isFrac = ~strcmpi(model.meta.fractureModel, 'matrix');
assert(any(strcmp(model.grid.kind, {'cart', 'vari', 'corner', 'connlist'})), ...
    'writeEclipseModel:fracGridKind', ...
    'Grid kind "%s" has no Eclipse form here.', model.grid.kind);

fid = fopen(incFile, 'w');
assert(fid > 0, 'writeEclipseModel:open', 'Could not open %s.', incFile);
cleaner = onCleanup(@() fclose(fid)); %#ok<NASGU>
w = @(varargin) fprintf(fid, varargin{:});

meta  = model.meta;
dims  = model.grid.dims;
props = model.props;
nTot  = prod(dims);

% ---------------------------------------------------------------- banner
w('-- =====================================================================\n');
w('-- MRST -> Eclipse grid description (generated by writeEclipseModel)\n');
w('-- GRID_FAMILY      : %s   (MRST type: %s)\n', meta.gridFamily, meta.gridType);
w('-- FRACTURE_MODEL   : %s\n', meta.fractureModel);
w('-- UNITS            : METRIC, permeability mD, lengths m\n');
w('-- BLOCKS           : %d x %d x %d = %d (%d inactive)\n', dims, ...
    nTot, meta.counts.inactive);
w('-- =====================================================================\n\n');

% ------------------------------------------------------------------ grid
switch model.grid.kind
    case 'corner'
        w('SPECGRID\n %d %d %d 1 F /\n\n', dims);
        localArray(fid, 'COORD', model.grid.coord, '%.6f');
        localArray(fid, 'ZCORN', model.grid.zcorn, '%.6f');

    case {'cart', 'vari'}
        % DXV/DYV/DZV give one value per column, row and layer respectively,
        % which is exactly the tensor description the model already holds.
        localArray(fid, 'DXV', model.grid.di, '%.6f');
        localArray(fid, 'DYV', model.grid.dj, '%.6f');
        localArray(fid, 'DZV', model.grid.dk, '%.6f');

        % TOPS for EVERY block, not just the top layer. Eclipse accepts the
        % NX*NY form, but it is ambiguous - a reader has to infer which
        % convention was used - and MRST's own reader expects one value per
        % block. Writing the true top depth of each block costs one array and
        % removes the guesswork.
        dz = model.grid.dk(:)';
        layerTop = model.grid.ztop + [0, cumsum(dz(1:end-1))];
        [~, ~, kk] = ind2sub(dims, (1:nTot)');
        localArray(fid, 'TOPS', layerTop(kk), '%.6f');

    case 'connlist'
        % Eclipse has no unstructured grid either, so the same
        % connection-list device is used: an Nc x 1 x 1 strip of unit blocks
        % whose geometry means nothing. PORV restores pore volume, TOPS the
        % depth, and the NNC list carries the entire connectivity.
        w('-- Connection-list pseudo-grid: Eclipse has no unstructured grid\n');
        w('-- type. Geometry is a placeholder - pore volume comes from PORV,\n');
        w('-- depth from TOPS, and all connectivity from the NNC list.\n');
        localArray(fid, 'DXV', ones(dims(1), 1), '%.6f');
        localArray(fid, 'DYV', 1, '%.6f');
        localArray(fid, 'DZV', 1, '%.6f');
        localArray(fid, 'TOPS', model.props.depth, '%.6f');

    otherwise
        error('writeEclipseModel:kind', ...
            'Grid kind %s has no Eclipse representation here.', model.grid.kind);
end

% ------------------------------------------------------------ properties
if meta.counts.inactive > 0
    localArray(fid, 'ACTNUM', double(props.active), '%d');
end
localArray(fid, 'PERMX', props.permi, '%.6e');
localArray(fid, 'PERMY', props.permj, '%.6e');
localArray(fid, 'PERMZ', props.permk, '%.6e');
localArray(fid, 'PORO',  props.poro,  '%.6f');

% ------------------------------------------- explicit connections and EDIT
% A connection-list grid needs the same treatment as a fracture model even
% when it carries no fractures: its geometry is a placeholder, so pore
% volume, depth and the whole connectivity have to be stated explicitly.
nNNC = 0; nMult = 0;
if isFrac || strcmp(model.grid.kind, 'connlist')
    % NNC belongs in GRID, before the EDIT section opens.
    %
    % Units: the model carries transmissibility in md.m, the unit the CMG
    % path uses. Eclipse METRIC wants cP.m3/(day.bar), so convert through SI
    % with MRST's own constants rather than a hand-derived factor.
    mdm = milli*darcy*meter;
    ecl = centi*poise*meter^3/(day*barsa);
    conn = model.conn;
    nNNC = size(conn, 1);
    if nNNC > 0
        w('-- %d embedded-fracture connections (trans in cP.m3/day/bar)\n', nNNC);
        w('NNC\n');
        fprintf(fid, ' %d %d %d  %d %d %d  %.8e /\n', ...
            [conn(:, 1:6), conn(:, 7)*(mdm/ecl)]');
        w('/\n\n');
    end

    % Seals between logical neighbours become MULT records. The model stores
    % them as [dir i j k value] with dir 1/2/3 = X/Y/Z, addressed at the
    % lower-indexed block, which is exactly what MULTX/Y/Z expect.
    nMult = size(model.mult, 1);
    if nMult > 0
        w('-- %d projection seals on matrix faces\n', nMult);
        dirKw = {'MULTX', 'MULTY', 'MULTZ'};
        for d = 1:3
            rows = model.mult(model.mult(:,1) == d, :);
            if isempty(rows), continue; end
            w('EQUALS\n');
            for q = 1:size(rows, 1)
                w(' ''%s'' %.8e %d %d %d %d %d %d /\n', dirKw{d}, rows(q,5), ...
                    rows(q,2), rows(q,2), rows(q,3), rows(q,3), rows(q,4), rows(q,4));
            end
            w('/\n\n');
        end
    end

    % ---- EDIT: pore volume, depth, and isolation of the padding ----------
    w('EDIT\n\n');
    w('-- True fracture pore volume. PORV overrides the porosity-times-bulk\n');
    w('-- calculation, so the value MRST computed transfers exactly.\n');
    localArray(fid, 'PORV', props.porvol, '%.8e');

    % A connection-list grid already stated its depths through TOPS above;
    % repeating them here would be a second, conflicting specification. The
    % padding layers of a structured fracture grid do need the override,
    % because their TOPS came from the placeholder layer geometry.
    if ~isempty(props.depth) && ~strcmp(model.grid.kind, 'connlist')
        w('-- True block depths; the padding geometry is a placeholder.\n');
        localArray(fid, 'DEPTH', props.depth, '%.6f');
    end

    w('-- Isolate the padding region: fracture cells communicate only\n');
    w('-- through the NNC records above.\n');
    for q = 1:numel(model.isolate)
        r = model.isolate(q).range;
        kw = strrep(model.isolate(q).keyword, '*TRANS', 'TRAN');
        w('EQUALS\n ''%s'' %g %d %d %d %d %d %d /\n/\n\n', kw, ...
            model.isolate(q).value, r(1), r(2), r(3), r(4), r(5), r(6));
    end
end

info = struct('include', incFile, 'dims', dims, ...
    'gridFamily', meta.gridFamily, 'fractureModel', meta.fractureModel, ...
    'counts', meta.counts, 'nNNC', nNNC, 'nMult', nMult);
end

%--------------------------------------------------------------------------
function localArray(fid, keyword, values, fmt)
% Eclipse free format: keyword on its own line, values wrapped, terminating
% slash. Values are written out in full rather than run-length compressed -
% the browser port has to reproduce this byte for byte, and two independent
% implementations of a compression heuristic is a bug waiting to happen.
fprintf(fid, '%s\n', keyword);
v = values(:);
perLine = 6;
n = numel(v);
full = perLine*floor(n/perLine);
if full > 0
    rowFmt = [repmat([' ' fmt], 1, perLine) '\n'];
    fprintf(fid, rowFmt, reshape(v(1:full), perLine, []));
end
if full < n
    fprintf(fid, [' ' fmt], v(full+1:end));
    fprintf(fid, '\n');
end
fprintf(fid, '/\n\n');
end
